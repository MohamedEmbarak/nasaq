"""Reproduce the pinned calendar data and independent conversion oracle offline.

First download the published artifact:
  python -m pip download --no-deps hijridate==2.3.0 -d .artifacts/calendar-research
Then run this script with its wheel path. No Python dependency is shipped to apps.
The artifact hash must match checked-in provenance; updates require source review.
"""
import hashlib
import json
from pathlib import Path
import sys
import zipfile

ROOT = Path(__file__).resolve().parents[1]
PROVENANCE = ROOT / 'packages/core/third-party/provenance.json'
meta = json.loads(PROVENANCE.read_text())
wheel = Path(sys.argv[1]).resolve()
if hashlib.sha256(wheel.read_bytes()).hexdigest() != meta['artifactSHA256']:
    raise SystemExit('Calendar artifact hash mismatch. Review provenance before updating.')
sys.path.insert(0, str(wheel))
from hijridate import Hijri, Gregorian  # noqa: E402
import datetime  # noqa: E402

starts = [Hijri(year, month, 1).to_julian()
          for year in range(1343, 1501) for month in range(1, 13)]
starts.append(Hijri(1500, 12, 30).to_julian() + 1)
source = ('/** Umm al-Qura month starts (integer Julian days), HijriDate 2.3.0.\n'
          ' * Copyright (c) 2018 Mohammed Alshehri. MIT; see ../third-party/hijridate-LICENSE.txt.\n'
          ' * Generated from the pinned published table, not astronomical approximations.\n'
          ' * Last entry is an exclusive sentinel. See provenance.json and docs/date-calendars.md. */\n'
          'export const UMALQURA_FIRST_YEAR = 1343;\n'
          'export const UMALQURA_LAST_YEAR = 1500;\n'
          'export const UMALQURA_MONTH_STARTS: readonly number[] = [\n'
          + ''.join('  ' + ', '.join(map(str, starts[i:i+12])) + ',\n'
                    for i in range(0, len(starts), 12)) + '];\n')
(ROOT / 'packages/core/src/ummalqura-data.ts').write_text(source)
with zipfile.ZipFile(wheel) as archive:
    (ROOT / 'packages/core/third-party/hijridate-LICENSE.txt').write_bytes(
        archive.read('hijridate-2.3.0.dist-info/LICENSE'))

# Expected output generated by the independently implemented, pinned Python
# converter, not by Nasaq's JavaScript calendar provider.
digest = hashlib.sha256()
first = datetime.date(1924, 8, 1)
days = starts[-1] - starts[0]
for offset in range(days):
    date = first + datetime.timedelta(days=offset)
    hijri = Gregorian(date.year, date.month, date.day).to_hijri()
    digest.update(f'{date.isoformat()}|{hijri.year}-{hijri.month}-{hijri.day}\n'.encode())
fixture = {'source': 'hijridate==2.3.0', 'artifactSHA256': meta['artifactSHA256'],
           'from': first.isoformat(), 'through': '2077-11-16', 'days': days,
           'serialization': 'YYYY-MM-DD|HijriYear-HijriMonth-HijriDay\\n (unpadded Hijri)',
           'conversionSHA256': digest.hexdigest()}
dest = ROOT / 'packages/core/test/fixtures/ummalqura-oracle.json'
dest.parent.mkdir(exist_ok=True)
dest.write_text(json.dumps(fixture, indent=2) + '\n')
print(f'Regenerated {len(starts)-1} months and oracle for {days} days.')
